/* Contratos de seguridad de la administración de usuarios sin conexión externa. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const session = read('src/lib/auth/session.ts')
const admin = read('src/lib/keycloak/admin.ts')
const http = read('src/lib/keycloak/http.ts')
const page = read('src/app/admin/page.tsx')
const usersApi = read('src/app/api/admin/usuarios/route.ts')
const userApi = read('src/app/api/admin/usuarios/[id]/route.ts')
const logout = read('src/components/auth/signout-button.tsx')
const menu = read('src/components/profile-menu.tsx')
assert.match(session, /readAccountPrivileges\(session\.user\.id\)/)
assert.match(session, /if \(!privileges\.enabled\) return null/)
assert.match(session, /if \(!session\.user\.isAdmin\) redirect\("\/"\)/)
assert.match(admin, /import "server-only"/)
assert.match(admin, /grant_type: "client_credentials"/)
assert.match(admin, /role-mappings\/realm/)
assert.match(admin, /CAMBIO_PERSONAL_EN_KEYCLOAK/)
assert.match(admin, /NO_PUEDE_DESHABILITARSE/)
assert.match(admin, /NO_PUEDE_RETIRARSE_ADMIN/)
assert.match(admin, /ULTIMO_ADMINISTRADOR/)
assert.match(admin, /target\.enabled !== true/)
assert.doesNotMatch(admin, /NEXT_PUBLIC_/)
assert.match(http, /if \(!session\.user\.isAdmin\)/)
assert.match(http, /request\.headers\.get\("origin"\)/)
assert.match(http, /origin !== new URL\(configured\)\.origin/)
assert.match(http, /"application\/json"/)
assert.match(usersApi, /await authorizeAdmin\(\)/)
assert.match(usersApi, /validateAdminMutation\(request\)/)
assert.match(userApi, /await authorizeAdmin\(\)/)
assert.match(userApi, /validateAdminMutation\(request\)/)
assert.match(page, /await requireAdminSession\(\)/)
assert.match(menu, /isAdmin && <DropdownMenuItem/)
assert.match(logout, /signOutFederated/)
assert.ok(fs.existsSync(path.join(root, 'src/app/api/auth/oidc-logout/route.ts')))
console.log('Admin contract: autorización de servidor, roles en vivo, CSRF y gestión segura: correcto')
